#!/usr/bin/env node
/**
 * Generates dist/enforce/opencode-plugin.mjs — the single-file OpenCode plugin
 * that `openflow init` installs.
 *
 * Why generate instead of shipping dist/enforce/opencode.js directly: that file
 * imports ./rules.js, and OpenCode loads plugins through its own Bun runtime.
 * A sibling import that fails to resolve there would disable enforcement
 * silently, which is exactly the failure mode OpenFlow refuses to accept. So
 * the policy is inlined at build time and the shipped plugin resolves nothing.
 *
 * Inputs (tsc output, must exist — run `pnpm run build` first):
 *   dist/enforce/rules.js     — the single hand-maintained policy source
 *   dist/enforce/opencode.js  — the thin adapter (its rules import is dropped)
 *
 * Fails loudly on any unexpected shape. Never emits a partial plugin.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DIST = path.resolve(__dirname, '..', 'dist', 'enforce');
const RULES = path.join(DIST, 'rules.js');
const ADAPTER = path.join(DIST, 'opencode.js');
const OUT = path.join(DIST, 'opencode-plugin.mjs');

function fail(message) {
  console.error(`✖ build-opencode-plugin: ${message}`);
  process.exit(1);
}

for (const [label, file] of [['rules', RULES], ['adapter', ADAPTER]]) {
  if (!fs.existsSync(file)) fail(`${label} not found at ${file} — run \`pnpm run build\` first`);
}

const rulesSrc = fs.readFileSync(RULES, 'utf8');
const adapterSrc = fs.readFileSync(ADAPTER, 'utf8');

// 1. Hoist the rules module's own imports (Node built-ins) to the top of the
//    bundle, then strip `export ` so its declarations become file-local.
const rulesImports = [];
const rulesBody = [];
for (const line of rulesSrc.split('\n')) {
  if (/^import\s/.test(line)) {
    rulesImports.push(line);
    continue;
  }
  rulesBody.push(line.replace(/^export\s+(function|const|let|class)\s/, '$1 '));
}

if (/^export\s/m.test(rulesBody.join('\n'))) {
  fail('rules.js still contains an unhandled `export` form after stripping — inliner needs updating');
}

// 2. Drop the adapter's rules import; keep everything else verbatim.
const adapterLines = adapterSrc.split('\n');
const rulesImportIdx = adapterLines.findIndex((l) => /^import\s.*['"]\.\/rules\.js['"]/.test(l));
if (rulesImportIdx === -1) fail('adapter does not import ./rules.js — inliner needs updating');
adapterLines.splice(rulesImportIdx, 1);

for (const line of adapterLines) {
  if (/^import\s/.test(line)) rulesImports.push(line);
}
const adapterBody = adapterLines.filter((l) => !/^import\s/.test(l));

// 3. Assemble: imports, inlined policy, adapter.
const banner = `// GENERATED by scripts/build-opencode-plugin.mjs — do not edit.
// Policy source: src/enforce/rules.ts. Adapter source: src/enforce/opencode.ts.
`;
const bundle = [
  banner,
  [...new Set(rulesImports)].join('\n'),
  '',
  '// ---- inlined policy (src/enforce/rules.ts) ----',
  rulesBody.join('\n'),
  '// ---- OpenCode adapter (src/enforce/opencode.ts) ----',
  adapterBody.join('\n'),
].join('\n');

if (!/export default/.test(bundle)) fail('generated plugin has no default export — refusing to emit');

fs.writeFileSync(OUT, bundle);
console.log(`✔ opencode plugin generated: ${path.relative(path.resolve(__dirname, '..'), OUT)} (${bundle.split('\n').length} lines)`);
